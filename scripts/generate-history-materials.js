function pad2(n) {
  return String(n).padStart(2, '0');
}

function renderToc(m) {
  const items = m.sections
    .map(
      (s) =>
        `        <li class="m-essay-toc__item"><span class="m-essay-toc__dot q-findings-dot q-findings-dot--10-coloring-grey" aria-hidden="true"></span><a class="m-essay-toc__link" href="#${s.id}">${s.title}</a></li>`,
    )
    .join('\n');

  return `<aside class="m-essay-toc" aria-label="Содержание">
      <p class="m-essay-toc__label">Содержание</p>
      <ol class="m-essay-toc__list">
${items}
      </ol>
    </aside>`;
}

function renderPhotos(photos) {
  if (!photos || !photos.length) return '';
  const encode = (file) => encodeURI(file);
  // Normalize: a flat array becomes one group; an array of arrays stays as groups.
  // photos: ['a.jpg', 'b.jpg']        → one row of two
  // photos: [['a.jpg'], ['b.jpg']]    → two singles stacked
  // photos: [['a.jpg', 'b.jpg'], ['c.jpg']] → row of two, then single
  const groups = Array.isArray(photos[0]) ? photos : [photos];

  const renderGroup = (group) => {
    if (group.length === 1) {
      return `              <figure class="m-photo-slot m-essay-photo"><div class="m-photo-slot__image"><img src="${encode(group[0])}" alt="" loading="lazy" decoding="async" /></div></figure>`;
    }
    const mod = group.length === 3 ? ' m-photo-row--three' : group.length === 4 ? ' m-photo-row--four' : '';
    const slots = group
      .map((p) => `                <figure class="m-photo-slot"><div class="m-photo-slot__image"><img src="${encode(p)}" alt="" loading="lazy" decoding="async" /></div></figure>`)
      .join('\n');
    return `              <div class="m-photo-row m-essay-photo-row${mod}">\n${slots}\n              </div>`;
  };

  return '\n' + groups.map(renderGroup).join('\n');
}

function renderSection(s) {
  const paras = s.paragraphs
    .map((p) => `              <p class="m-interview-section__prose">${p}</p>`)
    .join('\n');

  const pull = s.pullQuote
    ? `\n              <blockquote class="m-pull-quote"><p>${s.pullQuote}</p></blockquote>`
    : '';

  const raw = s.raw ? `\n              ${s.raw.trim()}` : '';
  const photos = renderPhotos(s.photos);

  return `            <section class="m-interview-section__chapter" id="${s.id}">
              <h3 class="m-essay-heading">${s.title}</h3>
${paras}${raw}${pull}${photos}
            </section>`;
}

