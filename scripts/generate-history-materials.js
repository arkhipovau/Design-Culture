function renderJournalCard(m) {
  // Split on sentence boundary: period+space followed by a capital letter (Cyrillic or Latin).
  // Prevents splitting on abbreviations like "род. 1932".
  const description = m.bio.split(/\.\s(?=[А-ЯЁA-Z])/u)[0] + '.';
  return `
          <article class="m-journal-card" data-tags="${m.tags}" data-href="./interviews/${m.slug}.html">
                      <a class="a-image-journal-link a-image-journal-link--m" href="./interviews/${m.slug}.html">
                        <img class="q-image-journal" width="440" height="458" src="../images/history/${m.slug}.jpg" alt="${m.author}" loading="lazy" decoding="async" />
                        <span class="a-arrow-button a-arrow-button--corner" aria-hidden="true"></span>
                      </a>
                      <div class="m-journal-card__content">
                        <div class="m-journal-card__header">
                          <h3 class="m-journal-card__author">${m.author}</h3>
                          <h4 class="m-journal-card__subtitle">${m.title}</h4>
                        </div>
                        <p class="m-journal-card__description">${description}</p>
                        <div class="m-journal-card__meta">${m.meta}</div>
                      </div>
                    </article>`;
}

