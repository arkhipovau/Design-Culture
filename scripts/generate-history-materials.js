function main() {
  // 1. Write HTML files to src/ and docs/
  for (const m of MATERIALS) {
    const html = renderHtml(m);
    const srcFile = path.join(ROOT, 'src/pages/interviews', `${m.slug}.html`);
    const docsFile = path.join(ROOT, 'docs/pages/interviews', `${m.slug}.html`);
    fs.writeFileSync(srcFile, html);
    fs.writeFileSync(docsFile, html);
    console.log(`wrote ${m.slug}.html (src + docs)`);
  }

  // 2. Update meta.json (idempotent)
  const metaPath = path.join(ROOT, 'content/interviews-meta.json');
  const meta = JSON.parse(fs.readFileSync(metaPath, 'utf8'));
  for (const m of MATERIALS) {
    if (!meta.interviews[m.slug]) {
      meta.interviews[m.slug] = {
        author: m.author,
        meta: m.meta,
        hero: `../../images/history/${m.slug}.jpg`,
        about: m.bio,
        links: m.links.map((l) => l.label),
        subtitle: m.title,
        images: [],
      };
    }
    if (!meta.order.includes(m.slug)) {
      meta.order.push(m.slug);
    }
  }
  fs.writeFileSync(metaPath, JSON.stringify(meta, null, 2) + '\n');
  console.log(`meta.json: ${Object.keys(meta.interviews).length} entries, order ${meta.order.length}`);

  // 3. Journal cards: only inject if missing (idempotent)
  for (const journalPath of [
    path.join(ROOT, 'src/pages/journal.html'),
    path.join(ROOT, 'docs/pages/journal.html'),
  ]) {
    let html = fs.readFileSync(journalPath, 'utf8');
    if (html.includes('data-href="./interviews/bauhaus.html"')) {
      console.log(`${path.basename(journalPath)}: history cards already present`);
      continue;
    }
    // Insert all 9 cards before </div></section> of the journal grid.
    const cards = MATERIALS.map(renderJournalCard).join('\n');
    const anchor = '</div>\n      </section>';
    const idx = html.indexOf(anchor);
    if (idx === -1) {
      console.error(`${path.basename(journalPath)}: anchor not found`);
      continue;
    }
    html = html.slice(0, idx) + '\n' + cards + '\n' + html.slice(idx);
    fs.writeFileSync(journalPath, html);
    console.log(`${path.basename(journalPath)}: inserted history cards`);
  }
}

main();
