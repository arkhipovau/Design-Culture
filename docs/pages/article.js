  function renderQA(container, list) {
    if (!list || !list.length) {
      container.style.display = 'none';
      container.innerHTML = '';
      return;
    }
    container.style.display = '';
    container.innerHTML = '';
    list.forEach(function (item) {
      var row = document.createElement('div');
      row.className = 'qa-row';
      row.innerHTML =
        '<div class="name">' +
        item.q +
        '</div><div class="answer">' +
        item.a +
        '</div><div></div>';
      container.appendChild(row);
    });
  }

  function renderMediaRow(container, items) {
    if (!items || !items.length) {
      container.style.display = 'none';
      container.innerHTML = '';
      return;
    }
    container.style.display = '';
    container.innerHTML = '';
    items.forEach(function (item) {
      var fig = document.createElement('figure');
      fig.className = 'media-item';
      fig.innerHTML = '<img src="' + item.src + '" alt="' + (item.title || 'Изображение') + '">';
      if (item.title || item.copyright) {
        var caption = document.createElement('figcaption');
        caption.innerHTML = (item.title || '') + (item.copyright ? '<br>' + item.copyright : '');
        fig.appendChild(caption);
      }
      container.appendChild(fig);
    });
  }

